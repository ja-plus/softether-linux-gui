export type Locale = 'zh' | 'en'

/**
 * 首屏语言与后端 `detect_system_locale()` 保持同一规则：
 * 仅中国大陆用中文，其余地区一律英文。
 *
 * 后端设置加载完成后仍会以 `settings.locale` 为准，这里只负责避免
 * 英文用户在首次渲染时先看到一闪而过的中文。
 */
function initialLocale(): Locale {
  if (typeof navigator === 'undefined') return 'en'
  const tag = (navigator.languages?.[0] ?? navigator.language ?? '').toLowerCase().replace(/_/g, '-')
  const mainland = tag === 'zh-cn' || tag.startsWith('zh-cn-') || tag.startsWith('zh-hans-cn')
  return mainland ? 'zh' : 'en'
}

export const locale = ref<Locale>(initialLocale())

/** 配置文件可能被手改成任意值，未知语言一律回落中文 */
export function normalizeLocale(value: unknown): Locale {
  return value === 'en' ? 'en' : 'zh'
}

/** 把语言落到 <html lang>，并触发所有依赖 locale 的渲染 */
export function applyLocale(value: unknown) {
  const next = normalizeLocale(value)
  locale.value = next
  if (typeof document !== 'undefined') {
    document.documentElement.lang = next === 'zh' ? 'zh-CN' : 'en'
  }
}

export function t(key: MessageKey, params?: Record<string, string | number | null | undefined>): string {
  const table = locale.value === 'en' ? en : zh
  const template = table[key] ?? zh[key] ?? key
  if (!params) return template
  return template.replace(/\{(\w+)\}/g, (_, name: string) => {
    const value = params[name]
    return value === null || value === undefined ? '' : String(value)
  })
}

// 首屏就把语言与 <html lang> 对齐，不必等设置异步加载
applyLocale(locale.value)
